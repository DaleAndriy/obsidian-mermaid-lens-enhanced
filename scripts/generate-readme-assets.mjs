import { readFile, writeFile, mkdir, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { build } from "esbuild";
import { Window } from "happy-dom";

const output = "assets/readme";
const temporary = await mkdtemp(join(tmpdir(), "mermaid-lens-readme-"));
await mkdir(output, { recursive: true });
try {
  const modulePath = join(temporary, "renderer.mjs");
  await build({ entryPoints: ["src/beautiful-renderer.ts"], bundle: true, platform: "node", format: "esm", outfile: modulePath });
  const { renderBeautifulDiagram } = await import(pathToFileURL(modulePath).href);
  const window = new Window();
  for (const language of ["en", "zh"]) {
    const suffix = language === "en" ? "" : "-zh";
    const source = await readFile(`${output}/example${suffix}.mmd`, "utf8");
    const diagram = renderBeautifulDiagram(`readme-example-${language}`, source, window.document)
      ?.replace(/mermaid-lens-\d+-\d+-/g, `readme-${language}-`);
    if (!diagram) throw new Error("README example could not be rendered");
    const document = new window.DOMParser().parseFromString(diagram, "image/svg+xml");
    const svg = document.documentElement;
    svg.setAttribute("role", "img");
    const title = document.createElementNS("http://www.w3.org/2000/svg", "title");
    title.textContent = language === "en" ? "A decision with two clearly separated branches" : "带有两条独立审核分支的流程图";
    svg.prepend(title);
    await writeFile(`${output}/example${suffix}.svg`, new window.XMLSerializer().serializeToString(svg).replace(/^[\t ]+$/gm, ""));
    const [,, width, height] = svg.getAttribute("viewBox").split(/\s+/).map(Number);
    for (const mobile of [false, true]) {
      const canvasWidth = mobile ? 600 : 1200, canvasHeight = mobile ? 660 : 440;
      const graphHeight = mobile ? 380 : 384;
      const graphWidth = width / height * graphHeight;
      svg.setAttribute("x", String(mobile ? (600 - graphWidth) / 2 : 700));
      svg.setAttribute("y", mobile ? "234" : "28");
      svg.setAttribute("width", String(graphWidth));
      svg.setAttribute("height", String(graphHeight));
      const x = mobile ? 32 : 48;
      const tagline = language === "en" ? "Clearer diagrams in Obsidian." : "让 Obsidian 里的流程图更清晰。";
      const markup = `<svg xmlns="http://www.w3.org/2000/svg" width="${canvasWidth}" height="${canvasHeight}" viewBox="0 0 ${canvasWidth} ${canvasHeight}" role="img" aria-labelledby="title desc">
  <title id="title">Mermaid Lens Enhanced</title>
  <desc id="desc">${tagline} ${title.textContent}. This example is generated by the plugin's renderer.</desc>
  <rect width="${canvasWidth}" height="${canvasHeight}" fill="#FFFFFF" rx="16"/>
  <g id="identity" transform="translate(0 ${mobile ? 0 : 32})" font-family="-apple-system, BlinkMacSystemFont, Segoe UI, PingFang SC, Microsoft YaHei, sans-serif">
    ${mobile ? "" : '<text x="48" y="52" font-size="18" letter-spacing="1.4" fill="#587184">OBSIDIAN / STANDARD MERMAID</text>'}
    <text x="${x}" y="${mobile ? 76 : 137}" font-size="${mobile ? 60 : 64}" font-weight="700" letter-spacing="-2" fill="#173C54">Mermaid Lens</text>
    <text x="${x}" y="${mobile ? 141 : 211}" font-size="${mobile ? 58 : 64}" font-weight="600" letter-spacing="-1.6" fill="#1769AA">Enhanced</text>
    <text x="${x}" y="${mobile ? 191 : 271}" font-size="${language === "zh" ? 25 : 26}" fill="#587184">${tagline}</text>
  </g>
  ${new window.XMLSerializer().serializeToString(svg)}
</svg>\n`;
      await writeFile(`${output}/hero${suffix}${mobile ? "-mobile" : ""}.svg`, markup.replace(/^[\t ]+$/gm, ""));
    }
  }
  console.log("Generated English and Chinese SVG heroes and actual renderer examples.");
} finally {
  await rm(temporary, { recursive: true, force: true });
}
